#!/usr/bin/env python3
"""Apply the authorized DLC unlock to an AssetRipper Assembly-CSharp source tree.

Usage:
    python -I apply_dlc_unlock.py --source <...\\Assets\\Scripts\\Assembly-CSharp> \
        --items work\\build_all\\generated\\dlc-items.csv \
        --recipe work\\build_all\\generated\\02-dlc-unlock

The patch is deliberately small and reproducible:
  1. StoreManager.cs becomes `public partial class` and calls UnlockOwnedDlc()
     immediately after SD_Load() in Awake().
  2. DlcUnlock.cs (generated) contains one ownership check per SaleType == 1
     item and calls the game's own private ProductSet(type, id, true) method.
Only numeric type/id data is written; no product names or game content.
"""
import argparse
import csv
import os


IS_METHOD = {
    "ClothesKazusa": "IsClothesKazusa",
    "ClothesSetuna": "IsClothesSetuna",
    "HeadAccessoryKazusa": "IsHeadAccessoryKazusa",
    "HeadAccessorySetuna": "IsHeadAccessorySetuna",
    "FaceAccessoryKazusa": "IsFaceAccessoryKazusa",
    "FaceAccessorySetuna": "IsFaceAccessorySetuna",
    "BG2D": "IsBG2D",
    "BG3D": "IsBG3D",
    "Effect": "IsEffect",
    "PVKazusa": "IsPVKazusa",
    "PVSetuna": "IsPVSetuna",
    "PVEdit": "IsPVEdit",
    "Spt": "IsSpt",
}


def generate_unlock(rows):
    lines = [
        "// PC port: one-time unlock of the owned paid DLC (SaleType == 1).",
        "// Generated by scripts/apply_dlc_unlock.py from the game's own Ac* tables.",
        "// It reuses StoreManager's private ProductSet(type, id, true), so the",
        "// bitfields and the CRC32+XOR share.bin format stay canonical.",
        "public partial class StoreManager",
        "{",
        "    public void UnlockOwnedDlc()",
        "    {",
        "        bool changed = false;",
    ]
    for row in rows:
        if int(row["SaleType"]) != 1:
            continue
        product_type = row["ProductType"]
        item_id = int(row["ID"])
        is_method = IS_METHOD[product_type]
        lines.append(
            f"        changed |= UnlockDlcItem(ProductType.{product_type}, {item_id}, {is_method}({item_id}));"
        )
    lines += [
        "        if (changed)",
        "        {",
        "            SD_Save();",
        "        }",
        "    }",
        "",
        "    private bool UnlockDlcItem(ProductType type, int id, bool alreadyOwned)",
        "    {",
        "        if (alreadyOwned)",
        "        {",
        "            return false;",
        "        }",
        "        ProductSet(type, id, true);",
        "        return true;",
        "    }",
        "}",
        "",
    ]
    return "\n".join(lines)


def patch_store_manager(path):
    with open(path, encoding="utf-8-sig") as handle:
        text = handle.read()
    changed = False
    if "public partial class StoreManager" not in text:
        old = "public class StoreManager : MonoBehaviour"
        if old not in text:
            raise SystemExit("StoreManager class declaration not found")
        text = text.replace(old, "public partial class StoreManager : MonoBehaviour", 1)
        changed = True
    if "UnlockOwnedDlc();" not in text:
        # Insert after the single SD_Load() call in Awake.
        needle = "\t\tSD_Load();"
        if needle not in text:
            raise SystemExit("SD_Load() call not found in StoreManager.Awake")
        text = text.replace(needle, needle + "\n\t\tUnlockOwnedDlc();", 1)
        changed = True
    if changed:
        with open(path, "w", encoding="utf-8", newline="\n") as handle:
            handle.write(text)
    return changed


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--source", required=True)
    parser.add_argument("--items", required=True)
    parser.add_argument("--recipe", required=True)
    args = parser.parse_args()
    with open(args.items, encoding="utf-8") as handle:
        rows = list(csv.DictReader(handle))
    unlock = generate_unlock(rows)
    os.makedirs(args.recipe, exist_ok=True)
    for target in (os.path.join(args.recipe, "DlcUnlock.cs"), os.path.join(args.source, "DlcUnlock.cs")):
        with open(target, "w", encoding="utf-8", newline="\n") as handle:
            handle.write(unlock)
    changed = patch_store_manager(os.path.join(args.source, "StoreManager.cs"))
    with open(os.path.join(args.recipe, "dlc-items.csv"), "w", encoding="utf-8", newline="\n") as handle:
        handle.write("ProductType,ID,CharaType,SaleType,WPValue\n")
        for row in rows:
            handle.write(
                f"{row['ProductType']},{row['ID']},{row['CharaType']},{row['SaleType']},{row['WPValue']}\n"
            )
    print("StoreManager patched" if changed else "StoreManager already patched")
    print("DlcUnlock.cs written to", args.source)
    print("sale1 items:", sum(1 for row in rows if int(row["SaleType"]) == 1))


if __name__ == "__main__":
    main()
