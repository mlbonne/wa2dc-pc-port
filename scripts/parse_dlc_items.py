#!/usr/bin/env python3
"""Extract DLC item tables from the decompiled Ac* classes.

Usage: python -I parse_dlc_items.py <decomp-Assembly-CSharp-dir> <out-dir>

Writes:
  dlc-items.csv   - one row per item with its ProductType mapping
  dlc-unlock.cs   - C# UnlockDlcItem(...) calls for SaleType == 1
Prints counts per category.
"""
import os
import re
import sys

# class name -> list of (chara_type, ProductType name)
CLASS_MAP = {
    "AcClothes": {1: "ClothesKazusa", 0: "ClothesSetuna"},
    "AcHeadAccessory": {1: "HeadAccessoryKazusa", 0: "HeadAccessorySetuna"},
    "AcFaceAccessory": {1: "FaceAccessoryKazusa", 0: "FaceAccessorySetuna"},
    "AcBG2D": {-1: "BG2D"},
    "AcBG3D": {-1: "BG3D"},
    "AcStageEffect": {-1: "Effect"},
    "AcPVData": {1: "PVKazusa", 0: "PVSetuna"},
    "AcPVEdit": {-1: "PVEdit"},
    "AcOthers": {-1: "Spt"},
}

BLOCK_RE = re.compile(r"new\s+InPurchaseData\s*\{(.*?)\}", re.S)
INT_RE = re.compile(r"(\w+)\s*=\s*(-?\d+)")


def parse_file(path):
    text = open(path, encoding="utf-8", errors="replace").read()
    items = []
    for block in BLOCK_RE.findall(text):
        values = {key: int(value) for key, value in INT_RE.findall(block)}
        if "ID" not in values:
            continue
        items.append(values)
    return items


def main():
    source_dir, out_dir = sys.argv[1], sys.argv[2]
    os.makedirs(out_dir, exist_ok=True)
    rows = []
    counts = {}
    for name in sorted(CLASS_MAP):
        path = os.path.join(source_dir, name + ".cs")
        if not os.path.exists(path):
            print("missing", path)
            continue
        for item in parse_file(path):
            chara = item.get("CharaType", -1)
            mapping = CLASS_MAP[name]
            if chara not in mapping:
                continue
            product_type = mapping[chara]
            rows.append((name, item["ID"], chara, item.get("SaleType", -1), item.get("WPValue", 0), product_type))
            if item.get("SaleType", -1) == 1:
                counts[product_type] = counts.get(product_type, 0) + 1
    with open(os.path.join(out_dir, "dlc-items.csv"), "w", encoding="utf-8", newline="\n") as handle:
        handle.write("class,ID,CharaType,SaleType,WPValue,ProductType\n")
        for row in rows:
            handle.write(",".join(str(value) for value in row) + "\n")
    with open(os.path.join(out_dir, "dlc-unlock.cs"), "w", encoding="utf-8", newline="\n") as handle:
        handle.write("// Generated by scripts/parse_dlc_items.py; all SaleType == 1 items.\n")
        for row in rows:
            if row[3] == 1:
                handle.write(f"UnlockDlcItem(ProductType.{row[5]}, {row[1]});\n")
    print("sale1 counts:", dict(sorted(counts.items())))
    print("total sale1:", sum(counts.values()))
    print("total items:", len(rows))


if __name__ == "__main__":
    main()
